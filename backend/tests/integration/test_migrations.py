import pytest
from alembic import command
from alembic.config import Config
from alembic.util.exc import AutogenerateDiffsDetected

from tests.conftest import alembic_config as make_alembic_config


@pytest.fixture
def alembic_config(migrated_postgres_url: str) -> Config:
    return make_alembic_config(migrated_postgres_url)


def test_upgrade_downgrade_upgrade(alembic_config: Config) -> None:
    command.upgrade(alembic_config, "head")
    command.downgrade(alembic_config, "base")
    command.upgrade(alembic_config, "head")


def test_models_match_migrations(alembic_config: Config) -> None:
    command.upgrade(alembic_config, "head")
    try:
        command.check(alembic_config)
    except AutogenerateDiffsDetected as exc:
        pytest.fail(f"Models and migrations differ; generate a revision:\n{exc}")
